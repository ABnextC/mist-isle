POLE_L = (0.15, 0.0, 1.0)
POLE_R = (-0.15, 0.0, 1.0)


def _feet(c, feet):
    n = c['n']
    for side in ('L', 'R'):
        home = FL if side == 'L' else FR
        ks = list(feet.get(side) or [(0, home)])
        # 끝에는 기본 자세로 돌아온다(다음 동작과 이어 붙기 쉽게)
        if max(k[0] for k in ks) < 1:
            last = max(k[0] for k in ks)
            ks.append((min(1.0, max(last + 0.25, 0.85)), home))
            if ks[-1][0] < 1:
                ks.append((1.0, home))
        T = keys_at(ks, n, False, 3)
        pole = np.tile(POLE_L if side == 'L' else POLE_R, (n, 1))
        c = leg_ik(c, side, T, pole=pole)
    return c


def mk(base, dur, hit, keys, feet=None, spin=None, ev=None, src='77_02+스킬'):
    e = {'hit': round(hit, 4)}
    if spin:
        e['spin'] = list(spin)
    if ev:
        e.update(ev)
    c = keyed_clip(base, dur, keys, loop=False, ev=e, src=src)
    return _feet(c, feet or {})



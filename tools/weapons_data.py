import json
import os
OUT = os.path.join(os.path.dirname(__file__), '..', 'data', 'weapons.json')

# 자리: (row, col). row마다 그 갈래에 찍은 점수(req)가 있어야 열린다
REQ = [0, 2, 4, 6, 10]
LAYOUT = {'a1': (0, 0), 'p1': (0, 1), 'a2': (0, 2), 'u1': (1, 0), 'p2': (1, 1), 'u2': (1, 2),
          'p3': (2, 0), 'a3': (2, 1), 'p4': (2, 2), 'p5': (3, 0), 'u3': (3, 1), 'ult': (4, 1)}

def tree(w, ti, tid, name, icon, desc, a, u, p, ult):
    nodes = []
    for k, (row, col) in LAYOUT.items():
        n = {'id': f'{w}_{tid}_{k}', 'weapon': w, 'tree': ti, 'row': row, 'col': col, 'req': REQ[row]}
        if k[0] == 'a':
            i = int(k[1]) - 1
            ab = dict(a[i][3])
            ab.setdefault('clip', f'sk_{w}_{tid}{i + 1}')
            n.update({'kind': 'active', 'name': a[i][0], 'icon': a[i][1], 'text': a[i][2], 'ab': ab})
        elif k == 'ult':
            n.update({'kind': 'ult', 'name': ult[0], 'icon': '🌟', 'text': ult[1], 'p': ult[2]})
        elif k[0] == 'u':
            i = int(k[1]) - 1
            n.update({'kind': 'up', 'name': u[i][0], 'icon': '⬆️', 'text': u[i][1], 'needs': f'{w}_{tid}_a{i + 1}', 'mod': u[i][2]})
        else:
            i = int(k[1]) - 1
            n.update({'kind': 'passive', 'name': p[i][0], 'icon': p[i][1], 'text': p[i][2], 'p': p[i][3]})
        nodes.append(n)
    return {'id': tid, 'name': name, 'icon': icon, 'desc': desc}, nodes

W = {}
NODES = []
def weapon(w, name, icon, desc, t0, t1):
    trees = []
    for ti, t in enumerate((t0, t1)):
        info, nodes = tree(w, ti, *t)
        trees.append(info)
        NODES.extend(nodes)
    W[w] = {'name': name, 'icon': icon, 'desc': desc, 'trees': trees}

